	const char* GetNetMessageName(netMessage::Type type)
	{
		const auto value = static_cast<std::uint32_t>(type);
		if (value > 0x8F)
			return "Invalid";

		const char* name = g_MessageNames[value];
		return name ? name : "Unknown";
	}
